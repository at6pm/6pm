import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build, type Plugin } from 'esbuild';

import { catalogues } from '../../packages/i18n/src/translate';
import {
  activityInk,
  DEFAULT_LOOK,
  paletteFor,
  paperInk,
  shareCardInk,
} from '../../packages/theme/src/index';

/**
 * Writes what the iOS side reads from the TypeScript packages, so Swift never holds its own copy
 * of a number rule, a word or a colour:
 *
 * - `targets/_shared/domain-native.js`: `@6pm/domain`'s native entry for JavaScriptCore
 * - `targets/_shared/<lang>.lproj/<Table>.strings`: i18n keys `native.<table>.*`; the
 *   `AppShortcuts` table goes to the target whose shortcut says it (`targets/intents`, or
 *   `targets/_app` for the app's own), keyed by the English phrase as Siri looks it up
 * - `locales/<lang>.json`: the permission prompts, i18n keys `native.permission.*`, and the
 *   Android launcher shortcuts' labels
 * - `targets/_shared/ThemeTokens.swift`: the fixed colours extensions draw with
 * - `targets/widgets/SurfaceAttributes.swift`: the Live Activity type, copied from the module
 * - `targets/_shared/GroupFiles.swift`: the App Group files, copied from the module
 *
 *   tsx tools/scripts/generate-native.ts           write every file
 *   tsx tools/scripts/generate-native.ts --check   fail when one is out of date
 */

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const mobile = path.join(root, 'apps/mobile');
const shared = path.join(mobile, 'targets/_shared');
const header = 'Generated by tools/scripts/generate-native.ts. Never edit by hand.';

type Catalogue = Readonly<Record<string, unknown>>;

/**
 * The languages Siri speaks, whose App Shortcut phrases are written for it. Siri has no Vietnamese
 * or Indonesian, so there it hears the English phrases; English is the Swift source itself.
 */
const SIRI_LANGUAGES: ReadonlySet<string> = new Set([
  'zh-Hans',
  'ja',
  'ko',
  'th',
  'es',
  'fr',
  'de',
]);

/** The Info.plist key each permission prompt fills. */
const PERMISSION_KEYS: Readonly<Record<string, string>> = {
  camera: 'NSCameraUsageDescription',
  microphone: 'NSMicrophoneUsageDescription',
  speech: 'NSSpeechRecognitionUsageDescription',
  photos: 'NSPhotoLibraryUsageDescription',
  photosAdd: 'NSPhotoLibraryAddUsageDescription',
  location: 'NSLocationWhenInUseUsageDescription',
};

function text(catalogue: Catalogue, key: string): string {
  const value = catalogue[key];
  if (typeof value !== 'string') throw new Error(`${key} must be a plain string for iOS`);
  return value;
}

/** Android string resources, by name, and the i18n key each one reads. */
const ANDROID_STRINGS: Readonly<Record<string, string>> = {
  sixpm_shortcut_scan: 'native.intents.scan.title',
  sixpm_shortcut_quick_add: 'native.intents.quickAdd.title',
  sixpm_widget_safe_name: 'native.surfaces.safeToday.name',
  sixpm_widget_safe_description: 'native.surfaces.safeToday.description',
  sixpm_widget_today_name: 'native.surfaces.todayList.name',
  sixpm_widget_today_description: 'native.surfaces.todayList.description',
  sixpm_widget_set_up: 'native.surfaces.setUp',
};

function permissionLocale(catalogue: Catalogue): string {
  const entries = Object.entries(PERMISSION_KEYS).map(([name, plistKey]): [string, string] => [
    plistKey,
    text(catalogue, `native.permission.${name}`),
  ]);
  // The prompts go under `ios` only: Android has its own permission wording, and these keys copied
  // into its per-language strings with no default fail the release build's lint. Under `android`,
  // the launcher shortcuts' labels and the widgets' names, whose English default
  // `plugins/with-android-shortcuts` writes.
  const android = Object.fromEntries(
    Object.entries(ANDROID_STRINGS).map(([name, key]): [string, string] => [
      name,
      text(catalogue, key),
    ]),
  );
  return `${JSON.stringify({ ios: Object.fromEntries(entries), android }, null, 2)}\n`;
}

const stringsLiteral = (value: string) =>
  `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;

/** The phrases of shortcuts that open the app, which the app itself declares. */
const APP_SHORTCUTS = new Set(['scan', 'scanToPay', 'quickAdd']);

/**
 * `native.surfaces.safeToday.name` → `_shared/<lang>.lproj/Surfaces.strings`, key
 * `safeToday.name`. `native.appShortcuts.*` → `AppShortcuts.strings` of the target that declares
 * the shortcut, keyed by the English phrase, only in a language Siri speaks.
 */
function stringsTables(lang: string, catalogue: Catalogue): Map<string, string> {
  const tables = new Map<string, string[]>();
  for (const key of Object.keys(catalogue).sort()) {
    const [scope, table, ...rest] = key.split('.');
    if (scope !== 'native' || table === undefined || table === 'permission') continue;
    const shortcut = table === 'appShortcuts';
    if (shortcut && !SIRI_LANGUAGES.has(lang)) continue;
    const titled = table.charAt(0).toUpperCase() + table.slice(1);
    // Only the target with the shortcut takes its phrases; another would warn about them.
    const dir = !shortcut
      ? shared
      : path.join(mobile, APP_SHORTCUTS.has(rest.join('.')) ? 'targets/_app' : 'targets/intents');
    const name = path.join(dir, `${lang}.lproj/${titled}.strings`);
    const lines = tables.get(name) ?? [];
    const id = shortcut ? text(catalogues.en, key) : rest.join('.');
    lines.push(`${stringsLiteral(id)} = ${stringsLiteral(text(catalogue, key))};`);
    tables.set(name, lines);
  }
  return new Map(
    [...tables].map(([name, lines]) => [name, `/* ${header} */\n${lines.join('\n')}\n`]),
  );
}

/** `#rrggbb` or `rgba(r,g,b,a)` as a SwiftUI colour. */
function swiftColor(css: string): string {
  const hex = /^#([0-9a-f]{6})$/i.exec(css);
  const rgba = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/.exec(
    css,
  );
  let channels: [number, number, number, number];
  if (hex?.[1]) {
    const n = Number.parseInt(hex[1], 16);
    channels = [(n >> 16) & 255, (n >> 8) & 255, n & 255, 1];
  } else if (rgba) {
    channels = [Number(rgba[1]), Number(rgba[2]), Number(rgba[3]), Number(rgba[4] ?? 1)];
  } else {
    throw new Error(`Cannot write ${css} as a Swift colour`);
  }
  const [r, g, b, a] = channels.map((c, i) => (i < 3 ? c / 255 : c).toFixed(4));
  return `Color(.sRGB, red: ${r}, green: ${g}, blue: ${b}, opacity: ${a})`;
}

/** The plain palette the free widgets and the share card use, by day and by night. */
const PLAIN_TOKENS = ['sheetSolid', 'ink', 'inkSoft', 'hair', 'accent', 'btnBg', 'btnFg'] as const;

function themeTokens(): string {
  const block = (name: string, tokens: Readonly<Record<string, string>>) =>
    [
      `  enum ${name} {`,
      ...Object.entries(tokens).map(([k, v]) => `    static let ${k} = ${swiftColor(v)}`),
      '  }',
    ].join('\n');
  const plain = (hour: number) => {
    const palette = paletteFor({ look: DEFAULT_LOOK, hour, serious: true });
    return Object.fromEntries(PLAIN_TOKENS.map((k) => [k, String(palette[k])]));
  };
  return [
    `// ${header}`,
    '// Colours from @6pm/theme for surfaces drawn outside the app.',
    'import SwiftUI',
    '',
    'enum ThemeTokens {',
    block('Paper', paperInk),
    block('PlainDay', plain(12)),
    block('PlainNight', plain(22)),
    block('Activity', activityInk),
    block('ShareCard', shareCardInk),
    '}',
    '',
  ].join('\n');
}

/**
 * zod re-exports every language's error messages; the extensions only ever show their own copy,
 * and zod loads English for itself, so the rest stay out of the bundle (about half its size).
 */
const withoutZodLocales: Plugin = {
  name: 'without-zod-locales',
  setup(context) {
    context.onResolve({ filter: /locales\/index\.js$/ }, (args) =>
      args.importer.includes(`${path.sep}zod${path.sep}`)
        ? { path: 'zod-locales', namespace: 'stub' }
        : undefined,
    );
    context.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({ contents: 'export {};' }));
  },
};

async function domainBundle(): Promise<string> {
  const result = await build({
    entryPoints: [path.join(root, 'packages/domain/src/native/entry.ts')],
    bundle: true,
    format: 'iife',
    globalName: 'SixpmDomain',
    target: 'es2020',
    platform: 'neutral',
    minify: true,
    legalComments: 'none',
    write: false,
    plugins: [withoutZodLocales],
    banner: { js: `// ${header}` },
  });
  const [file] = result.outputFiles;
  if (!file) throw new Error('esbuild wrote nothing');
  return file.text;
}

/** A module source the extensions compile too: ActivityKit and the group need the same code. */
function moduleCopy(name: string): string {
  const source = path.join(mobile, `modules/surfaces/ios/${name}`);
  return `// ${header}\n// Copied from modules/surfaces/ios/${name}.\n${readFileSync(source, 'utf8')}`;
}

async function outputs(): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  files.set(path.join(shared, 'domain-native.js'), await domainBundle());
  files.set(path.join(shared, 'ThemeTokens.swift'), themeTokens());
  files.set(
    path.join(mobile, 'targets/widgets/SurfaceAttributes.swift'),
    moduleCopy('SurfaceAttributes.swift'),
  );
  files.set(path.join(shared, 'GroupFiles.swift'), moduleCopy('GroupFiles.swift'));
  for (const [lang, catalogue] of Object.entries(catalogues)) {
    files.set(path.join(mobile, `locales/${lang}.json`), permissionLocale(catalogue));
    for (const [file, body] of stringsTables(lang, catalogue)) files.set(file, body);
  }
  return files;
}

const check = process.argv.includes('--check');
const stale: string[] = [];
for (const [file, body] of await outputs()) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (current === body) continue;
  if (check) {
    stale.push(path.relative(root, file));
  } else {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, body);
    console.log(`wrote ${path.relative(root, file)}`);
  }
}
if (stale.length > 0) {
  console.error(`Out of date; run tsx tools/scripts/generate-native.ts:\n${stale.join('\n')}`);
  process.exit(1);
}
