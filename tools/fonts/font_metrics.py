"""Writes the line metrics iOS sets each bundled font on, and how far its glyphs reach past them.

    python3 tools/fonts/font_metrics.py

Reads the hhea ascender, descender and line gap of every font in `apps/mobile/assets/fonts` (the
metrics Core Text lays a line out with), and the highest and lowest ink of the letters, figures and
Vietnamese marks the app sets (Ẫ, Ỗ, ỵ…), at every weight a variable file keeps. iOS draws a text
only inside its box, so a mark that rises above the ascender needs room the line does not give.
Writes `apps/mobile/src/ui/type/font-metrics.generated.ts`. Run it after `build_fonts.py`.
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "apps/mobile/assets/fonts"
OUT = ROOT / "apps/mobile/src/ui/type/font-metrics.generated.ts"

BASE = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789$€£¥₫%&@#"
VIET = "ĂÂĐÊÔƠƯăâđêôơư"
TONED = "AĂÂEÊIOÔƠUƯYaăâeêioôơuưy"
TONES = "̣̀́̃̉"


def letters() -> list[str]:
    """Every letter Vietnamese writes with its tone mark, precomposed, beside the plain ones."""
    import unicodedata

    toned = [unicodedata.normalize("NFC", base + tone) for base in TONED for tone in TONES]
    return list(BASE) + list(VIET) + [c for c in toned if len(c) == 1]


def ink(font: TTFont, chars: list[str]) -> tuple[float, float]:
    """The highest and lowest ink of `chars`, in font units (y up)."""
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    top, bottom = 0.0, 0.0
    for char in chars:
        name = cmap.get(ord(char))
        if name is None:
            continue
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        if pen.bounds:
            top = max(top, pen.bounds[3])
            bottom = min(bottom, pen.bounds[1])
    return top, bottom


def instances(font: TTFont) -> list[TTFont]:
    """The font at each corner of its axes (a static font is its own one instance)."""
    if "fvar" not in font:
        return [font]
    axes = [(a.axisTag, a.minValue, a.maxValue) for a in font["fvar"].axes]
    corners: list[dict[str, float]] = [{}]
    for tag, lo, hi in axes:
        corners = [{**c, tag: v} for c in corners for v in (lo, hi)]
    return [instancer.instantiateVariableFont(font, corner, inplace=False) for corner in corners]


def main() -> None:
    chars = letters()
    lines = []
    for path in sorted(FONTS.glob("*.ttf")):
        if path.stem.startswith("MaterialSymbols"):
            continue
        font = TTFont(path)
        em = font["head"].unitsPerEm
        hhea = font["hhea"]
        line = (hhea.ascent - hhea.descent + hhea.lineGap) / em
        reach = [ink(instance, chars) for instance in instances(font)]
        top = max(t for t, _ in reach) / em
        bottom = -min(b for _, b in reach) / em
        lines.append(
            f"  '{path.stem.replace('-Variable', '')}': "
            f"{{ line: {line:.4f}, ascent: {hhea.ascent / em:.4f}, "
            f"descent: {-hhea.descent / em:.4f}, inkTop: {top:.4f}, inkBottom: {bottom:.4f} }},"
        )
    OUT.write_text(
        "// Generated by tools/fonts/font_metrics.py from the bundled fonts. Do not edit.\n\n"
        "/**\n"
        " * Per font family, in ems: the height of one line iOS sets it in, the ascent and descent that\n"
        " * line is made of, and how high and low its letters, figures and Vietnamese marks reach from\n"
        " * the baseline, at any weight.\n"
        " */\n"
        "export const FONT_METRICS: Readonly<\n"
        "  Record<\n"
        "    string,\n"
        "    {\n"
        "      readonly line: number;\n"
        "      readonly ascent: number;\n"
        "      readonly descent: number;\n"
        "      readonly inkTop: number;\n"
        "      readonly inkBottom: number;\n"
        "    }\n"
        "  >\n"
        "> = {\n" + "\n".join(lines) + "\n};\n"
    )


if __name__ == "__main__":
    main()
